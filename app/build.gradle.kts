// Release signing reads from keystore.properties (gitignored, not committed) so the
// real keystore path/passwords never land in source control. See
// keystore.properties.example and the Play Store publishing guide for how to create it.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}

